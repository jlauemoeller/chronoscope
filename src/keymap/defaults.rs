//! The default bindings (product §5) with their help metadata, in help order.

use super::{Action, Context};

/// One row of the default keymap.
pub(super) struct DefaultBinding {
    pub context: Context,
    pub action: Action,
    /// The action name used in `[keys.<context>]`.
    pub name: &'static str,
    pub keys: &'static [&'static str],
    pub group: &'static str,
    pub description: &'static str,
}

const fn row(
    context: Context,
    action: Action,
    name: &'static str,
    keys: &'static [&'static str],
    group: &'static str,
    description: &'static str,
) -> DefaultBinding {
    DefaultBinding {
        context,
        action,
        name,
        keys,
        group,
        description,
    }
}

